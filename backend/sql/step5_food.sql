-- ========== 9. 食材百科表 food ==========
CREATE TABLE IF NOT EXISTS `food` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `name` VARCHAR(50) NOT NULL COMMENT '食物名称',
  `alias` VARCHAR(100) NULL COMMENT '别名，搜索用',
  `category` VARCHAR(30) NOT NULL COMMENT '分类：谷薯/肉蛋/蔬菜/水果/乳制品/豆制品/饮品零食',
  `calorie` DECIMAL(6,1) NOT NULL DEFAULT 0 COMMENT '每100g热量(kcal)',
  `protein` DECIMAL(5,1) NOT NULL DEFAULT 0 COMMENT '每100g蛋白质(g)',
  `carb` DECIMAL(5,1) NOT NULL DEFAULT 0 COMMENT '每100g碳水(g)',
  `fat` DECIMAL(5,1) NOT NULL DEFAULT 0 COMMENT '每100g脂肪(g)',
  `fiber` DECIMAL(5,1) NULL COMMENT '膳食纤维(g)',
  `sodium` DECIMAL(7,1) NULL COMMENT '钠(mg)',
  `standard_portion` VARCHAR(50) NULL COMMENT '常见份量，如 1个约50g',
  `description` VARCHAR(500) NULL COMMENT '简介/食用建议',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_food_name` (`name`),
  KEY `idx_food_category` (`category`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '食材百科';

